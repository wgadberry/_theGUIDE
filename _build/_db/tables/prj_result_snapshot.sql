CREATE TABLE `prj_result_snapshot` (
  `id` char(36) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT (uuid()),
  `project_id` char(36) COLLATE utf8mb4_unicode_ci NOT NULL,
  `parent_snapshot_id` char(36) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'Version chain — points to prior snapshot',
  `tool_type` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT 'bubblemap | wallet_tx',
  `subject_address` varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT 'Wallet or contract address under investigation',
  `version` smallint unsigned NOT NULL DEFAULT '1',
  `is_latest` tinyint NOT NULL DEFAULT '1',
  `result_gz` mediumblob NOT NULL COMMENT 'gzip-compressed JSON result payload',
  `result_hash` char(64) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT 'SHA-256 of uncompressed payload — change detection',
  `label` varchar(120) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'Optional user-supplied label for this snapshot',
  `result_metadata` json DEFAULT NULL,
  `meta_tx_count` bigint GENERATED ALWAYS AS (cast(json_unquote(json_extract(`result_metadata`,concat(_utf8mb4'$.summary[',ifnull(json_unquote(json_search(`result_metadata`,_utf8mb4'one',_utf8mb4'count',NULL,_utf8mb4'$.summary[*].name')),_utf8mb4'NULL'),_utf8mb4'].value'))) as signed)) VIRTUAL,
  `captured_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `archived_at` datetime(3) DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `prj_rs_uq_version` (`project_id`,`subject_address`,`tool_type`,`version`),
  KEY `prj_rs_fk_parent` (`parent_snapshot_id`),
  KEY `prj_rs_idx_project` (`project_id`),
  KEY `prj_rs_idx_subject` (`subject_address`),
  KEY `prj_rs_idx_tool_type` (`tool_type`),
  KEY `prj_rs_idx_is_latest` (`is_latest`),
  KEY `prj_rs_idx_result_hash` (`result_hash`),
  KEY `prj_rs_idx_archived_at` (`archived_at`),
  KEY `prj_rs_idx_captured_at` (`captured_at`),
  KEY `prj_rs_idx_meta_type` ((cast(json_extract(`result_metadata`,_utf8mb4'$.summary[*].type') as char(32) array))),
  CONSTRAINT `prj_rs_fk_parent` FOREIGN KEY (`parent_snapshot_id`) REFERENCES `prj_result_snapshot` (`id`),
  CONSTRAINT `prj_rs_fk_project` FOREIGN KEY (`project_id`) REFERENCES `prj` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Versioned, compressed result payloads from BubbleMap and Wallet Tx tools';
